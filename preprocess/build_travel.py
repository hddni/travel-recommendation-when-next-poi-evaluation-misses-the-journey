"""Build the A (routine-removed) dataset. Keeps only travel check-ins.

The labeling rules live in one place, dataset/daily_label.py. In summary:

    Stage 1 (per category)
        A  rvr >= 0.5  AND  uvr <= 0.25   -> all routine   (removed here)
        B  rvr <  0.5  AND  uvr >  0.25   -> all travel    (kept here)
        C  the rest (the two metrics conflict) / E undecidable -> to stage 2

    Stage 2 (per check-in, only for C/E)
        Split by relative repetition compared to other users who visited the same venue.
        Venues with no comparison group (|U_v|=1) apply the stage-1 thresholds per venue.

    rvr(v) = fraction of the venue's visitors who visited 2+ times  (higher = more routine)
    uvr(v) = unique users / check-ins                               (higher = more travel)

A' (routine) is built by build_routine.py and is the **exact complement**. Since both
scripts call the same daily_label.label(), it is guaranteed that before k-core the
check-in sets are disjoint and their union is the raw data.

Output:
    dataset/foursquare-<scope>-travel/
        foursquare-<scope>-travel.inter   user_id, item_id, timestamp, local_timestamp
        foursquare-<scope>-travel.item    item_id, venue_category_id, venue_category, lat, lon
        category_quadrants.csv              per-category uvr/rvr/quadrant/source
    recbole/properties/dataset/foursquare-<scope>-travel.yaml

Unrelated to run_recbole; meant to be run once before training to build the datasets.

Usage:
    python dataset/build_travel.py
    python dataset/build_travel.py --scopes KR,JP --kcore 5
"""

