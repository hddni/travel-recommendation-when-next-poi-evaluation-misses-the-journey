# Scopes to build. "ALL" is worldwide; the rest are ISO 3166-1 alpha-2 country codes.
# To add more countries later, just add them here.
SCOPES = ["ALL", "DE", "KR", "SG", "US", "JP"]

# Countries included in the "ALL" scope are defined only in venue_category_stats.py.
#   The labeling reference (ALL.csv) and the dataset scope must share the same country set,
#   so writing them separately in two places silently applies the wrong reference if they diverge.
from venue_category_stats import ALL_COUNTRIES  # noqa: E402

# Stage 1/stage 2 thresholds are defined only in one place, dataset/daily_label.py.
#   RVR_THRESHOLD=0.5  UVR_THRESHOLD=0.25  MIN_VENUES_USED=10  REL_TAU=4.0
from daily_label import (  # noqa: E402
    MIN_VENUES_USED, REL_TAU, RVR_THRESHOLD, TOURISM_WHITELIST, UVR_THRESHOLD,
)
import daily_label  # noqa: E402


# k-core (both users and items at least this many times). Use the dict below to vary it per country.
KCORE = 5
KCORE_OVERRIDE = {}     # e.g. {"US": 10, "JP": 10}


# ═══════════════════════════════════════════════════════════════════════════

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
#  Code lives in preprocess/, data in dataset/.
DATA = os.path.join(ROOT, "dataset")
SRC_DIR = os.path.join(DATA, "foursquare")
POI_FILE = os.path.join(SRC_DIR, "raw_POIs.txt")
CHECKIN_FILE = os.path.join(SRC_DIR, "dataset_WWW_Checkins_anonymized.txt")
STATS_DIR = os.path.join(DATA, "venue_category_stats")
PROPS_DIR = os.path.join(ROOT, "recbole", "properties", "dataset")

INTER_HEADER = ["user_id:token", "item_id:token", "timestamp:float",
                "local_timestamp:float"]

# Fix corrupted category names in raw_POIs.txt (must match venue_category_stats.py)
CATEGORY_FIXES = {"Caf�": "Café", "Caf��": "Café"}


def dataset_yaml(name, kcore, note):
    return f"""# {note}
# Generated by: dataset/build_travel.py  ({kcore}-core already applied)
# item = venueId, venue_category/lat/lon = side information

# Atomic File Format
field_separator: "\\t"
seq_separator: " "

# Basic Information
USER_ID_FIELD: user_id
ITEM_ID_FIELD: item_id
TIME_FIELD: timestamp
RATING_FIELD: ~
LABEL_FIELD: label
NEG_PREFIX: neg_

# Sequential Model Needed
ITEM_LIST_LENGTH_FIELD: item_length
LIST_SUFFIX: _list
MAX_ITEM_LIST_LENGTH: 50
POSITION_FIELD: position_id

# Selectively Loading
#   latitude/longitude are required for RoG / circular-interval analysis.
#   local_timestamp (tz-corrected local time) is in the file but not loaded by default.
load_col:
    inter: [user_id, item_id, timestamp]
    item: [item_id, venue_category_id, latitude, longitude]
unload_col: ~
unused_col: ~

# Filtering  ({kcore}-core already applied at generation -> no further filtering)
rm_dup_inter: ~
val_interval: ~
filter_inter_by_user_or_item: True
user_inter_num_interval: "[0,inf)"
item_inter_num_interval: "[0,inf)"

# Preprocessing
#   Never enable this: normalizing lat/lon makes RoG computation impossible.
normalize_field: ~
normalize_all: ~
"""


def scope_subset(chk, scope, all_countries=None):
    """Select only the check-ins in the given scope.

    If scope == "ALL", restrict to all_countries; if that is None, use the whole world.
    """
    if scope != "ALL":
        return chk[chk["country"] == scope]
    if all_countries is None:
        return chk
    return chk[chk["country"].isin(all_countries)]


def load_source():
    """Read POIs and check-ins and return (poi, chk). Times are already tz-corrected."""
    t0 = time.time()
    print(f"Reading POIs: {POI_FILE}", flush=True)
    poi = pd.read_csv(
        POI_FILE, sep="\t", header=None,
        names=["venue", "latitude", "longitude", "cat", "country"],
        dtype={"venue": str, "cat": str, "country": str},
        quoting=3, on_bad_lines="skip", engine="c",
    )
    poi["cat"] = poi["cat"].fillna("").replace(CATEGORY_FIXES)
    print(f"  POIs {len(poi):,}  ({time.time() - t0:.0f}s)", flush=True)

    print(f"Reading check-ins: {CHECKIN_FILE}", flush=True)
    chk = pd.read_csv(
        CHECKIN_FILE, sep="\t", header=None,
        names=["user_id", "item_id", "utc_time", "tz_offset"],
        dtype={"user_id": str, "item_id": str, "utc_time": str},
        quoting=3, on_bad_lines="skip", engine="c",
    )
    print(f"  checkins {len(chk):,}  ({time.time() - t0:.0f}s)", flush=True)

    chk["country"] = chk["item_id"].map(dict(zip(poi["venue"], poi["country"])))
    chk = chk.dropna(subset=["country"])
    chk = attach_timestamp(chk, "utc_time", parse_foursquare_time)
    tz = pd.to_numeric(chk["tz_offset"], errors="coerce").fillna(0).astype("int64")
    chk["local_timestamp"] = chk["timestamp"] + tz * 60
    chk = chk.drop(columns=["utc_time", "tz_offset"])
    print(f"  Time conversion done ({time.time() - t0:.0f}s)", flush=True)
    return poi, chk


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--scopes", type=str, default=",".join(SCOPES))
    parser.add_argument("--rvr", type=float, default=RVR_THRESHOLD)
    parser.add_argument("--uvr", type=float, default=UVR_THRESHOLD)
    parser.add_argument("--min_venues_used", type=int, default=MIN_VENUES_USED)
    parser.add_argument("--rel_tau", type=float, default=REL_TAU,
                        help="Stage 2: threshold on the ratio relative to other users at the same venue")
    parser.add_argument("--kcore", type=int, default=KCORE)
    parser.add_argument(
        "--all_countries", type=str, default=",".join(ALL_COUNTRIES),
        help="Countries to include in the ALL scope (comma-separated). 'world' = the entire world.",
    )
    parser.add_argument("--out_root", type=str, default=DATA,
                    help="Parent directory in which dataset folders are created. To separate\n"
                         "datasets by threshold combination, pass dataset/<combo_name>")
    args = parser.parse_args()
    scopes = [s.strip().upper() for s in args.scopes.split(",") if s.strip()]
    all_cc = (None if args.all_countries.strip().lower() == "world"
              else [c.strip().upper() for c in args.all_countries.split(",") if c.strip()])
    if "ALL" in scopes:
        print(f"ALL scope: {'entire world' if all_cc is None else f'{len(all_cc)} countries ' + ','.join(all_cc)}")

    print(f"Stage 1 (category): A routine = rvr >= {args.rvr} AND uvr <= {args.uvr} / "
          f"B travel = rvr < {args.rvr} AND uvr > {args.uvr}  "
          f"(own-country reliability floor n_venues_used >= {args.min_venues_used})")
    print(f"Stage 2 (check-in): relative ratio >= {args.rel_tau}, if no comparison group "
          f"count >= {daily_label.solo_min_count(args.uvr)}")
    print(f"k-core: {args.kcore} (override {KCORE_OVERRIDE})")
    print(f"Travel whitelist: {len(TOURISM_WHITELIST)} entries (only reverts A -> C)\n")

    poi, chk = load_source()
    # Must index by venue before map. If you build a Series with a RangeIndex and
    # attach venue via index=, pandas tries to align indices and everything becomes NaN.
    poi_idx = poi.set_index("venue")
    coords = poi_idx[["latitude", "longitude"]]
    slug = poi_idx["cat"].map(slug_token)
    cats = pd.DataFrame({"venue_category_id": slug, "venue_category": slug})
    v2cat = poi_idx["cat"]
    del poi

    for scope in scopes:
        name = f"foursquare-{scope.lower()}-travel"
        k = KCORE_OVERRIDE.get(scope, args.kcore)
        sub = scope_subset(chk, scope, all_cc)
        if len(sub) == 0:
            print(f"[{name}] no data in this scope - skipped", flush=True)
            continue

        print(f"\n=== {name}  ({k}-core) ===")
        params = daily_label.category_params(scope, args.rvr, args.uvr,
                                             args.min_venues_used)
        cat_col = sub["item_id"].map(v2cat)
        origin = len(sub)
        sub = sub[cat_col.notna() & (cat_col != "")]
        sub = drop_invalid_coords(sub, "item_id", coords)

        #  Routine/travel labeling. travel (A) keeps only travel.
        is_daily, st = daily_label.label(sub, v2cat, params, rel_tau=args.rel_tau,
                                         uvr_th=args.uvr)
        daily_label.report(st)
        sub = sub[~is_daily]
        print(f"    cumulative: {origin:,} -> {len(sub):,} ({len(sub)/origin*100:.1f}% retained)")

        sub = sub[["user_id", "item_id", "timestamp", "local_timestamp"]].copy()
        sub = iterative_kcore(sub, "user_id", "item_id", k)
        if len(sub) == 0:
            print(f"    No data left after {k}-core.", flush=True)
            continue

        inter = sub.sort_values(["user_id", "timestamp"])
        item = build_item_frame(inter["item_id"].values, coords, cats)
        out_dir = os.path.join(args.out_root, name)
        write_dataset(out_dir, name, inter, item, INTER_HEADER)
        params.to_csv(os.path.join(out_dir, "category_quadrants.csv"),
                      encoding="utf-8-sig")
        os.makedirs(PROPS_DIR, exist_ok=True)
        with open(os.path.join(PROPS_DIR, f"{name}.yaml"), "w", encoding="utf-8") as f:
            note = f"Foursquare {scope} - routine categories removed (A)"
            if scope == "ALL" and all_cc:
                note += f" / restricted to {len(all_cc)} countries ({','.join(all_cc)})"
            f.write(dataset_yaml(name, k, note))
        report(name, inter, item, kcore=k)
        print(f"    -> {out_dir}", flush=True)


if __name__ == "__main__":
    main()
