"""Export per-category UVR/RVR results to Excel (for visualizations such as scatter plots).

    UVR (unique visitor ratio)   = |U_v| / N_v                   higher = more travel
    RVR (repetitive visit ratio) = |{u : count(u,v) >= 2}| / |U_v|
                                                                 higher = more routine
    Category value = mean of per-venue values (only venues with >= min_checkins=10 check-ins)

Usage:
    python dataset/export_category_stats.py                # ALL
    python dataset/export_category_stats.py --scopes ALL,US,JP,KR,SG,DE
    python dataset/export_category_stats.py -o out.xlsx
"""

import argparse
import os
import sys

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

import daily_label as dl  # noqa: E402

STATS = os.path.join(ROOT, "dataset", "venue_category_stats")


def build(scope):
    t = pd.read_csv(os.path.join(STATS, f"{scope}.csv"), encoding="utf-8-sig")
    t = t.set_index("venueCategory")
    p = dl.category_params(scope, verbose=False)
    out = pd.DataFrame({
        "venueCategory": t.index,
        "UVR": t["uvr"].values,                 # higher = more travel
        "RVR": t["rvr"].values,                 # higher = more routine
        "quadrant": p["quadrant"].reindex(t.index).values,
        "n_venues_used": t["n_venues_used"].values,   # number of venues included in the mean
        "n_venues": t["n_venues"].values,             # total number of venues in that category
        "checkins": t["checkins"].values,             # all check-ins (regardless of filter)
        "n_pairs": t["n_pairs"].values,               # unique (user, venue) pairs
        "n_pairs_rvr": t["n_pairs_rvr"].values,       # of those, pairs visited 2+ times
        "stat_source": p["source"].reindex(t.index).values,   # own country / ALL fallback
        "rvr_all_legacy": t["rvr_all"].values,        # old definition (mean visits per user)
    })
    out["checkin_share_%"] = out["checkins"] / out["checkins"].sum() * 100
    return out.sort_values("UVR", ascending=False, na_position="last")


def meta_sheet():
    return pd.DataFrame([
        ("UVR", "|U_v| / N_v — unique visitors of venue v / total check-ins. Higher = more travel"),
        ("RVR", f"|{{u : count(u,v) >= {dl.RVR_THETA}}}| / |U_v| — share of revisitors among visitors. Higher = more routine"),
        ("category aggregation", "Mean of per-venue values. Venues with fewer than 10 check-ins (min_checkins) are excluded"),
        ("quadrant A", f"RVR >= {dl.RVR_THRESHOLD} AND UVR <= {dl.UVR_THRESHOLD}  → strong routine (decided at stage 1)"),
        ("quadrant B", f"RVR <  {dl.RVR_THRESHOLD} AND UVR >  {dl.UVR_THRESHOLD}  → strong travel (decided at stage 1)"),
        ("quadrant C", "The two metrics disagree → deferred to stage 2 (check-in-level) labeling"),
        ("quadrant D", f"RVR < {dl.RVR_THRESHOLD} AND UVR <= {dl.UVR_THRESHOLD} — empty in every scope"),
        ("quadrant E", f"Unlabelable (insufficient samples in both own-country and ALL)"),
        ("stat_source", f"Whether own-country stats are used. Falls back to ALL.csv if n_venues_used < {dl.MIN_VENUES_USED}"),
        ("n_venues_used", "Number of venues actually included in the mean. Smaller = less stable value"),
        ("rvr_all_legacy", "Old-definition RVR = total check-ins / unique pairs (mean visits per user). For comparison"),
        ("whitelist", "Not applied (USE_WHITELIST = False)"),
        ("generated by", "python dataset/export_category_stats.py"),
    ], columns=["item", "description"])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--scopes", type=str, default="ALL")
    ap.add_argument("-o", "--out", type=str,
                    default=os.path.join(ROOT, "category_stats.xlsx"))
    a = ap.parse_args()
    scopes = [s.strip().upper() for s in a.scopes.split(",") if s.strip()]

    with pd.ExcelWriter(a.out, engine="openpyxl") as w:
        meta_sheet().to_excel(w, sheet_name="README", index=False)
        for s in scopes:
            d = build(s)
            d.to_excel(w, sheet_name=s, index=False)
            ws = w.sheets[s]
            for col, width in zip("ABCDEFGHIJKL",
                                  (34, 10, 10, 10, 15, 11, 12, 11, 13, 12, 15, 15)):
                ws.column_dimensions[col].width = width
            ws.freeze_panes = "B2"
            q = d["quadrant"].value_counts()
            print(f"  {s:>4}: categories {len(d):>4}  "
                  f"A {int(q.get('A',0)):>3} / B {int(q.get('B',0)):>3} / "
                  f"C {int(q.get('C',0)):>3} / E {int(q.get('E',0)):>3}", flush=True)
        w.sheets["README"].column_dimensions["A"].width = 18
        w.sheets["README"].column_dimensions["B"].width = 90
    print(f"\nSaved: {a.out}")


if __name__ == "__main__":
    main()
